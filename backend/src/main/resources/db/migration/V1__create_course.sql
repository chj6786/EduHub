-- FR-01~03: 교육과정과 회차
CREATE TABLE course (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(200) NOT NULL,
    category    VARCHAR(50)  NOT NULL,
    description TEXT,
    status      VARCHAR(20)  NOT NULL,
    CONSTRAINT ck_course_status CHECK (status IN ('OPEN', 'CLOSED'))
);

CREATE TABLE course_session (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id  BIGINT       NOT NULL,
    start_date DATE         NOT NULL,
    place      VARCHAR(200) NOT NULL,
    capacity   INT          NOT NULL,
    status     VARCHAR(20)  NOT NULL,
    CONSTRAINT fk_course_session_course FOREIGN KEY (course_id) REFERENCES course (id),
    CONSTRAINT ck_course_session_capacity CHECK (capacity > 0),
    CONSTRAINT ck_course_session_status CHECK (status IN ('OPEN', 'CLOSED'))
);

-- PostgreSQL은 FK에 인덱스를 자동으로 만들지 않는다. 과정별 회차 조회(FR-02)용.
CREATE INDEX idx_course_session_course_id ON course_session (course_id);
